def set_run_font(run, font_name="TH SarabunPSK", size_pt=16, bold=False, italic=False, color=None):
    run.font.name = font_name
    run.font.size = Pt(size_pt)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:ascii'), font_name)
    rFonts.set(qn('w:hAnsi'), font_name)
    rFonts.set(qn('w:cs'), font_name)
    rFonts.set(qn('w:eastAsia'), font_name)

def add_p(doc, text="", font_name="TH SarabunPSK", size_pt=16, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.THAI_JUSTIFY, space_before=0, space_after=3, line_spacing=1.1, first_line_indent_cm=0, color=None):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    if first_line_indent_cm > 0:
        pf.first_line_indent = Cm(first_line_indent_cm)
    if text:
        run = p.add_run(text)
        set_run_font(run, font_name=font_name, size_pt=size_pt, bold=bold, italic=italic, color=color)
    return p

def add_speaker_p(doc, speaker, text, font_name="TH SarabunPSK", size_pt=16, space_after=3, first_line_indent_cm=1.25):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.THAI_JUSTIFY
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.1
    pf.first_line_indent = Cm(first_line_indent_cm)
    
    r_speaker = p.add_run(speaker + " ")
    set_run_font(r_speaker, font_name=font_name, size_pt=size_pt, bold=True)
    
    r_text = p.add_run(text)
    set_run_font(r_text, font_name=font_name, size_pt=size_pt, bold=False)
    return p

def add_resolution_p(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.THAI_JUSTIFY
    pf = p.paragraph_format
    pf.space_before = Pt(2)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.1
    pf.first_line_indent = Cm(1.25)
    
    r_label = p.add_run("มติที่ประชุม: ")
    set_run_font(r_label, font_name="TH SarabunPSK", size_pt=16, bold=True, color=RGBColor(0, 51, 102))
    
    r_text = p.add_run(text)
    set_run_font(r_text, font_name="TH SarabunPSK", size_pt=16, bold=False)
    return p

def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)

def set_cell_border(cell, **kwargs):
    """
    kwargs: top, bottom, left, right
    values: {"val": "single", "sz": "4", "color": "CCCCCC"}
    """
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        edge_data = kwargs.get(edge)
        if edge_data:
            tag = 'w:{}'.format(edge)
            element = OxmlElement(tag)
            element.set(qn('w:val'), edge_data.get('val', 'single'))
            element.set(qn('w:sz'), str(edge_data.get('sz', 4)))
            element.set(qn('w:space'), '0')
            element.set(qn('w:color'), edge_data.get('color', 'auto'))
            tcBorders.append(element)
    tcPr.append(tcBorders)

