/**
 * ฟังก์ชันผู้ช่วยอัจฉริยะวิเคราะห์และแนะนำปัญหาอุปสรรคและแนวทางแก้ไข
 */
export function getSmartProblemSolution(riskCode = '', activity = '', period = '6month') {
  const code = (riskCode || '').toUpperCase().trim();
  const text = `${riskCode} ${activity}`.toLowerCase();
  const p = period || '6month';

  let key = null;
  if (text.includes('pdpa') || text.includes('สารบรรณ')) key = 'pdpa';
  else if (text.includes('กู้ภัย') || text.includes('สาธารณภัย') || text.includes('อัคคีภัย') || text.includes('ภัยแล้ง') || text.includes('อุทกภัย')) key = 'disaster';
  else if (text.includes('ita') || text.includes('ทุจริต') || text.includes('โปร่งใส')) key = 'ita';
  else if (text.includes('ภาษี') || text.includes('จัดเก็บ') || text.includes('ltax')) key = 'tax';
  else if (text.includes('จัดซื้อจัดจ้าง') || text.includes('พัสดุ') || text.includes('ว 614') || text.includes('ว614')) key = 'procurement';
  else if (text.includes('ktb') || text.includes('เบิกจ่ายเงิน') || text.includes('gfmis') || text.includes('e-payment')) key = 'ktb';
  else if (text.includes('สะพาน') || text.includes('ท่อระบายน้ำ') || text.includes('ท่อ')) key = 'drainage';
  else if (text.includes('ถนน') || text.includes('คสล')) key = 'road';
  else if (text.includes('factor') || text.includes('ราคากลาง') || text.includes('ราคาวัสดุ')) key = 'factorf';
  else if (text.includes('ประปา') || text.includes('น้ำประปา')) key = 'water';
  else if (text.includes('ไฟฟ้า') || text.includes('ไฟส่องสว่าง') || text.includes('solar')) key = 'light';
  else if (text.includes('นม') || text.includes('อาหารเสริม')) key = 'milk';
  else if (text.includes('สพฐ') && text.includes('อาหาร')) key = 'schoollunch';
  else if (text.includes('อาหารกลางวัน') || text.includes('ศพด')) key = 'lunch';
  else if (text.includes('อุดหนุน') || text.includes('รายหัว') || text.includes('การเรียนการสอน')) key = 'subsidy';
  else if (text.includes('สมศ') || text.includes('หลักสูตร') || text.includes('ปฐมวัย') || text.includes('ประกันคุณภาพ')) key = 'curriculum';
  else if (text.includes('ประเพณี') || text.includes('วัฒนธรรม') || text.includes('สงกรานต์') || text.includes('บั้งไฟ')) key = 'tradition';
  else if (text.includes('เบี้ยยังชีพ') || text.includes('ผู้สูงอายุ') || text.includes('คนพิการ')) key = 'welfare';
  else if (text.includes('เปราะบาง') || text.includes('ยากไร้') || text.includes('สงเคราะห์')) key = 'vulnerable';

  if (key && FANGKHAM_PROBLEM_SOLUTION_LIBRARY[key]) {
    return FANGKHAM_PROBLEM_SOLUTION_LIBRARY[key][p] || FANGKHAM_PROBLEM_SOLUTION_LIBRARY[key]['6month'];
  }

  // Fallback default
  if (p === '12month') {
    return 'การดำเนินงานบรรลุผลสำเร็จครบถ้วนตามแผนงานตลอดปีงบประมาณ ไม่มีปัญหาอุปสรรคคงค้าง';
  } else if (p === '3month') {
    return 'อยู่ระหว่างดำเนินการตามแผนงานในไตรมาสที่ 1 มีการเตรียมความพร้อมตามมาตรการ';
  }
  return 'อยู่ระหว่างดำเนินการตามแผนงานรอบ 6 เดือน มีการประสานงานและกำกับติดตามอย่างต่อเนื่อง';
}

